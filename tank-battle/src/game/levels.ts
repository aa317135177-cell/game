export interface LevelDef {
  name: string;
  layout: string[];
}

function createLayout(rows: string[]): string[] {
  if (rows.length !== 13 || rows.some((row) => row.length !== 13)) {
    throw new Error('关卡必须是 13x13');
  }
  return rows;
}

